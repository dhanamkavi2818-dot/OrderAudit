
package com.foodfactory.orderaudit;

import com.lowagie.text.Document;
import com.lowagie.text.Element;
import com.lowagie.text.Font;
import com.lowagie.text.Paragraph;
import com.lowagie.text.Phrase;
import com.lowagie.text.pdf.PdfPCell;
import com.lowagie.text.pdf.PdfPTable;
import com.lowagie.text.pdf.PdfWriter;

import org.springframework.stereotype.Service;

import java.io.ByteArrayOutputStream;
import java.math.BigDecimal;

@Service
public class InvoicePdfService {

    public byte[] generatePdf(Invoice invoice) {

        ByteArrayOutputStream output =
                new ByteArrayOutputStream();

        Document document = new Document();

        try {
            PdfWriter.getInstance(document, output);
            document.open();

            Font titleFont = new Font(
                    Font.HELVETICA, 20, Font.BOLD);

            Paragraph title = new Paragraph(
                    "GST TAX INVOICE", titleFont);

            title.setAlignment(Element.ALIGN_CENTER);
            title.setSpacingAfter(20);
            document.add(title);

            document.add(new Paragraph(
                    "Invoice Number: " +
                    invoice.getInvoiceNumber()));

            document.add(new Paragraph(
                    "Invoice Date: " +
                    invoice.getInvoiceDate()));

            document.add(new Paragraph(" "));

            SalesOrder order = invoice.getSalesOrder();

            document.add(new Paragraph(
                    "Customer: " +
                    order.getCustomer().getName()));

            document.add(new Paragraph(
                    "State: " +
                    order.getCustomer().getState()));

            document.add(new Paragraph(" "));

            PdfPTable table = new PdfPTable(4);
            table.setWidthPercentage(100);

            addCell(table, "Product");
            addCell(table, "Quantity");
            addCell(table, "Unit Price");
            addCell(table, "Amount");

            addCell(table,
                    order.getProduct().getProductName());

            addCell(table,
                    String.valueOf(order.getQuantity()));

            addCell(table,
                    order.getProduct()
                            .getSellingPrice().toString());

            addCell(table,
                    invoice.getTaxableAmount().toString());

            document.add(table);

            document.add(new Paragraph(" "));

            addAmount(document, "Taxable Amount",
                    invoice.getTaxableAmount());

            addAmount(document, "CGST",
                    invoice.getCgstAmount());

            addAmount(document, "SGST",
                    invoice.getSgstAmount());

            addAmount(document, "IGST",
                    invoice.getIgstAmount());

            addAmount(document, "Grand Total",
                    invoice.getTotalAmount());

            document.add(new Paragraph(" "));

            document.add(new Paragraph(
                    "Generated by OrderAudit System"));

        } catch (Exception e) {
            throw new IllegalStateException(
                    "Unable to generate invoice PDF", e);
        } finally {
            document.close();
        }

        return output.toByteArray();
    }

    private void addCell(PdfPTable table, String value) {
        PdfPCell cell = new PdfPCell(
                new Phrase(value));
        cell.setPadding(8);
        table.addCell(cell);
    }

    private void addAmount(
            Document document,
            String label,
            BigDecimal amount) throws Exception {

        document.add(new Paragraph(
                label + ": INR " + amount));
    }
}
